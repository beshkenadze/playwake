#!/usr/bin/env bash
# Playwake installer for SteamOS / Steam Deck.
#
# Installs the app and the bundled GStreamer runtime into ~/.local/share/playwake,
# verifies them, then adds the non-Steam shortcut with the library cover, hero and
# icon. It needs no sudo and changes no system package: the bundle carries the
# plugins SteamOS lacks. Run it from Desktop Mode, because writing shortcuts.vdf
# requires Steam to be closed, which would end a Game Mode session.
set -euo pipefail

bundle_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
dir="$HOME/.local/share/playwake"
assume_yes=0
do_shortcut=1
restart_steam=1

usage() {
    cat <<'EOF'
Usage: install.sh [options]
  --dir DIR             install directory (default ~/.local/share/playwake)
  --yes, -y             do not ask before closing Steam
  --no-shortcut         skip the Steam shortcut and artwork
  --no-restart-steam    leave Steam closed after writing the shortcut
  --help                show this help
EOF
}

while [[ $# -gt 0 ]]; do
    case $1 in
        --dir) dir=$2; shift 2 ;;
        --dir=*) dir=${1#*=}; shift ;;
        --yes|-y) assume_yes=1; shift ;;
        --no-shortcut) do_shortcut=0; shift ;;
        --no-restart-steam) restart_steam=0; shift ;;
        --help|-h) usage; exit 0 ;;
        *) echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
    esac
done

die() { echo "error: $*" >&2; exit 1; }

# SteamOS supervises Steam with a user unit; killing the client directly
# makes the session restart it. Stop/start the unit when it exists.
steam_unit=0
if systemctl --user cat steam-launcher.service >/dev/null 2>&1; then
    steam_unit=1
fi

close_steam() {
    if [[ $steam_unit == 1 ]]; then
        systemctl --user stop steam-launcher.service || die "could not stop steam-launcher.service"
    else
        pkill -15 -x steam 2>/dev/null || true
    fi
}

start_steam() {
    if [[ $steam_unit == 1 ]]; then
        systemctl --user start steam-launcher.service || die "could not start steam-launcher.service"
    else
        nohup steam -silent >/dev/null 2>&1 &
        disown 2>/dev/null || true
    fi
}

[[ $(uname -s) == Linux ]] || die "this installer targets Linux/SteamOS"
[[ $(uname -m) == x86_64 ]] || die "x86_64 only (got $(uname -m))"
command -v python3 >/dev/null || die "python3 is required"
# Game Mode restarts Steam whenever it exits, clobbering shortcuts.vdf.
# The env var is absent in SSH sessions, so also check the session target.
if [[ $do_shortcut == 1 ]] &&
    { [[ -n ${GAMESCOPE_WAYLAND_DISPLAY:-} ]] ||
      [[ $(systemctl --user is-active gamescope-session.target 2>/dev/null) == active ]]; }; then
    die "Game Mode detected. Switch to Desktop Mode and re-run (closing Steam ends the session)."
fi
mkdir -p "$dir"
dir=$(cd -- "$dir" && pwd)
if pid=$(pgrep -x playwake | head -1); then
    running_exe=$(readlink -f "/proc/$pid/exe" 2>/dev/null || true)
    if [[ -n $running_exe && $running_exe == "$dir/"* ]]; then
        die "Playwake is running from $dir; close it first"
    fi
fi

log="$dir/install.log"
say() { printf '%s\n' "$*" | tee -a "$log"; }

version=dev
[[ -f "$bundle_dir/VERSION" ]] && version=$(cat "$bundle_dir/VERSION")

say "==> Installing Playwake $version into $dir"
[[ -f "$bundle_dir/playwake" ]] || die "bundle is missing the playwake binary"
[[ -d "$bundle_dir/runtime" ]] || die "bundle is missing the private runtime"
mkdir -p "$dir/assets/branding" "$dir/packaging"
install -m755 "$bundle_dir/playwake" "$dir/playwake"
if [[ -f "$bundle_dir/playwake-media" ]]; then
    install -m755 "$bundle_dir/playwake-media" "$dir/playwake-media"
fi
install -m755 "$bundle_dir/launch-steamos.sh" "$dir/launch-steamos.sh"
install -m644 "$bundle_dir"/assets/branding/*.png "$dir/assets/branding/"
install -m644 "$bundle_dir/packaging/steam_shortcut.py" "$dir/packaging/"
install -m755 "$bundle_dir/packaging/install.sh" "$bundle_dir/packaging/uninstall.sh" "$dir/packaging/"
rm -rf "$dir/runtime"
cp -a "$bundle_dir/runtime" "$dir/runtime"

# src/media.rs turns ALLY_GST_RUNTIME into GST_PLUGIN_PATH and LD_LIBRARY_PATH
# for the media worker, so this one variable selects the bundled plugins.
cat > "$dir/env.sh" <<EOF
# Generated by install.sh. Sourced by launch-steamos.sh.
export ALLY_GST_RUNTIME="$dir/runtime/usr/lib"
EOF

say "==> Verification"
runtime_lib="$dir/runtime/usr/lib"
verify_output=$(GST_PLUGIN_PATH="$runtime_lib/gstreamer-1.0${GST_PLUGIN_PATH:+:$GST_PLUGIN_PATH}" \
    LD_LIBRARY_PATH="$runtime_lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" \
    "$dir/playwake-media" --selftest 2>&1 || true)
say "$verify_output"

check() {
    local label=$1
    shift
    if "$@" >/dev/null 2>&1; then
        say "[ok]   $label"
    else
        say "[FAIL] $label"
    fi
}
check "/dev/dri/renderD128 (VA-API)" test -e /dev/dri/renderD128
check "libvulkan.so.1 (GPUI + GStreamer Vulkan)" bash -c 'ldconfig -p | grep -q libvulkan.so.1'
check "xprop (Gamescope focus)" command -v xprop
check "playwake shared libraries" bash -c '! ldd "$1" | grep -q "not found"' _ "$dir/playwake"
if [[ -f "$dir/playwake-media" ]]; then
    check "playwake-media shared libraries" bash -c \
        'LD_LIBRARY_PATH="$2${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" ldd "$1" | grep -q "not found" && exit 1 || exit 0' \
        _ "$dir/playwake-media" "$runtime_lib"
fi
if grep -q '\[FAIL\]' <<<"$verify_output"; then
    say "Some checks failed; see $log. The install is kept so you can debug it."
fi

shortcut_json=""
closed_steam=0
steam_was_running=0
if pgrep -x steam >/dev/null 2>&1; then
    steam_was_running=1
fi

if [[ $do_shortcut == 1 ]]; then
    say "==> Steam shortcut and artwork"
    if [[ $steam_was_running == 1 ]]; then
        if [[ $assume_yes != 1 ]]; then
            printf 'Close Steam now to write the shortcut? [y/N] '
            read -r answer </dev/tty || die "non-interactive shell; re-run with --yes"
            case $answer in
                y|Y) ;;
                *) die "Steam must be closed to write shortcuts.vdf; re-run with --yes" ;;
            esac
        fi
        say "Closing Steam (it rewrites shortcuts.vdf on exit)..."
        close_steam
        closed_steam=1
        for _ in $(seq 1 60); do
            pgrep -x steam >/dev/null 2>&1 || break
            sleep 1
        done
        if pgrep -x steam >/dev/null 2>&1; then
            die "Steam did not exit; close it manually and re-run"
        fi
    fi
    shortcut_json=$(python3 "$dir/packaging/steam_shortcut.py" install --dir "$dir" --json)
    say "Shortcut appid: $(python3 -c 'import json,sys; print(json.loads(sys.argv[1])["appid_signed"])' "$shortcut_json")"
    say "Artwork: $(python3 -c 'import json,sys; print(", ".join(json.loads(sys.argv[1])["artwork"]))' "$shortcut_json")"
fi

python3 - "$dir" "$version" "$shortcut_json" <<'PY'
import json
import sys
import time
from pathlib import Path

install_dir, version, shortcut = sys.argv[1], sys.argv[2], sys.argv[3]
manifest = {
    "app": "playwake",
    "version": version,
    "dir": install_dir,
    "installed_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
}
if shortcut:
    manifest["shortcut"] = json.loads(shortcut)
Path(install_dir, "install.json").write_text(json.dumps(manifest, indent=2) + "\n")
PY

if [[ $restart_steam == 1 && $closed_steam == 1 ]]; then
    say "Starting Steam..."
    start_steam
fi

say "==> Done"
say "Installed: $dir"
if [[ $do_shortcut == 1 ]]; then
    say "Switch to Game Mode and launch Playwake from the library."
else
    say "Run: $dir/launch-steamos.sh"
fi
say "Log: $log"